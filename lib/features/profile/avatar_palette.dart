class AvatarPaletteColorMapper extends ColorMapper {
  const AvatarPaletteColorMapper(this.paletteIndex);

  final int paletteIndex;

  @override
  Color substitute(
    String? id,
    String elementName,
    String attributeName,
    Color color,
  ) {
    final colorIndex = _baseAvatarColors.indexOf(color.toARGB32());
    if (colorIndex == -1) return color;
    return Color(avatarPalettes[paletteIndex.clamp(0, 20).toInt()][colorIndex]);
  }
}

class HowBuddyAvatar extends StatelessWidget {
  const HowBuddyAvatar({
    required this.paletteIndex,
    required this.size,
    super.key,
  });

  final int paletteIndex;
  final double size;

  @override
  Widget build(BuildContext context) => SvgPicture.asset(
    'assets/icon/cropped_how_buddy.svg',
    width: size,
    height: size,
    colorMapper: AvatarPaletteColorMapper(paletteIndex),
  );
}
